// The public marketing landing at "/". No backend, no auth, no model: it pitches
// in-browser screening (/screen) and the local-first KYC workstation (/customers)
// and routes a visitor to whichever they want.
//
// Copy is i18n'd: the display strings live in locales/en/landing.json under the
// "landing" namespace, and the data arrays below hold catalog KEYS (resolved via
// t() at render). The big KPI figure line (num/prefix/unit) is DATA, not copy.
//
// HONESTY: every KPI below is a real number, not marketing fiction.
//   • $0 backend infra        — the /screen path makes zero backend calls after sync.
//   • ~{modelSizeMb} MB matcher — GENERATED by scripts/gen-demo-stats.mjs from a
//                                 statSync of public/models/.../model_quantized.onnx.
//   • live list entries       — READ at runtime from the verified signed catalog
//                                 (EngineRuntime.catalogOnlyLists: no model boot,
//                                 no list download — catalog chunk only), so
//                                 the count is whatever is published right now.
//                                 Until it arrives, or if the read fails, the tile
//                                 names the lists without any number — never a
//                                 hard-coded or fixture count.
//   • 0 bytes PII leave       — the query is matched in-tab; nothing typed is sent.

/** The one live read the landing makes: the verified signed list catalog. */
export interface CatalogSource {
	catalogLists(): Promise<ReadonlyArray<CatalogListInfo>>;
	dispose(): Promise<void>;
}

/** Production source: a catalog-only read (the model never boots and no list
 * downloads — the sync is scoped to the signed catalog, ~123 KB on production). */
function engineCatalogSource(): CatalogSource {
	const runtime = new EngineRuntime();
	const config = configFromEnv(import.meta.env);
	return {
		catalogLists: () => runtime.catalogOnlyLists(config),
		dispose: () => runtime.dispose(),
	};
}

