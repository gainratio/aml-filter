/** The verified catalog, or null while loading / after a failed read. */
function useLiveCatalog(
	makeSource: () => CatalogSource,
): ReadonlyArray<CatalogListInfo> | null {
	const [lists, setLists] = useState<ReadonlyArray<CatalogListInfo> | null>(
		null,
	);
	// Pinned at mount: one catalog read (and one runtime) per landing visit, even
	// if a caller passes a fresh factory on every render.
	const [makeOnce] = useState(() => makeSource);
	useEffect(() => {
		let cancelled = false;
		const source = makeOnce();
		source
			.catalogLists()
			.then((read) => {
				if (!cancelled && read.length > 0) setLists(read);
			})
			// A failed read keeps the number-free statement; nothing to surface.
			.catch(() => undefined);
		return () => {
			cancelled = true;
			void source.dispose().catch(() => undefined);
		};
	}, [makeOnce]);
	return lists;
}

function LiveListsTile({
	lists,
}: {
	readonly lists: ReadonlyArray<CatalogListInfo> | null;
}) {
	const { t, i18n } = useTranslation(["landing", "common"]);
	if (lists === null) {
		return (
			<div className="landing__tile">
				<div className="landing__tile-label">{t("metrics.lists.fallback")}</div>
				<div className="landing__tile-sub">
					{t("metrics.lists.fallbackSub")}
				</div>
			</div>
		);
	}
	const total = lists.reduce((sum, list) => sum + list.entitiesCount, 0);
	const names = lists.map((list) => listName(list.id, t, list.title));
	return (
		<div className="landing__tile">
			<div className="landing__tile-num">
				{new Intl.NumberFormat(i18n.language).format(total)}
			</div>
			<div className="landing__tile-label">
				{t("metrics.lists.label", { count: lists.length })}
			</div>
			<div className="landing__tile-sub">{names.join(" · ")}</div>
		</div>
	);
}

