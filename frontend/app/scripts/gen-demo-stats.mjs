// Prebuild: derive the landing page's build-time KPI — the size of the
// in-browser matcher model — from the committed file so it can never silently
// drift. It used to be a hand-copied literal in LandingPage.tsx (a drift hazard:
// re-export the model and the page lies). This script stats the committed
// quantized ONNX and emits a typed module the page imports.
//
//   • model size MB = statSync(public/models/.../model_quantized.onnx) bytes → MB
//
// The sanctions entry count is deliberately NOT generated here: the landing reads
// it live from the verified signed catalog at runtime. A build-time count could
// only come from a fixture, and a fixture count on a live product's front page is
// a fabricated figure.
//
// Run by the app's `prebuild` (alongside download-model) and `pretest` hooks so
// the generated module always exists for builds and Vitest. The generated file is
// committed too (so the repo always has a valid one), but every build regenerates
// it — keeping it honest. Fail-loud: a missing model file aborts with a non-zero
// exit rather than emitting a fake number.

import { mkdir, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The committed quantized ONNX matcher whose on-disk size the landing advertises. */
export function modelPath() {
	const here = dirname(fileURLToPath(import.meta.url));
	return join(
		here,
		"..",
		"public",
		"models",
		"Xenova",
		"all-MiniLM-L6-v2",
		"onnx",
		"model_quantized.onnx",
	);
}

/** Where the generated, typed stats module lands (imported by LandingPage). */
export function outputPath() {
	const here = dirname(fileURLToPath(import.meta.url));
	return join(here, "..", "src", "generated", "landing-stats.ts");
}

/** Bytes → whole MB (decimal, 1e6), rounded to the nearest MB. */
export function bytesToMb(bytes) {
	return Math.round(bytes / 1e6);
}

/** Derive the typed DemoStats from the model byte count. */
export function computeStats(modelBytes) {
	return { modelSizeMb: bytesToMb(modelBytes) };
}

/** Render the generated TypeScript module source for a DemoStats value. */
export function renderModule(stats) {
	return `// GENERATED by scripts/gen-demo-stats.mjs — do not edit.
// The landing page's build-time KPI, derived from the committed quantized ONNX
// matcher so it can never silently drift. (List entry counts are read live from
// the signed catalog, never generated.) Regenerated on every build (prebuild)
// and before tests (pretest); committed so the repo always has a valid copy.

/** The measured KPIs the public landing page renders. */
export interface DemoStats {
	/** Size of the in-browser MiniLM matcher (model_quantized.onnx), in whole MB. */
	readonly modelSizeMb: number;
}

export const DEMO_STATS: DemoStats = {
	modelSizeMb: ${stats.modelSizeMb},
};
`;
}

/** stat a source file's byte size, failing loudly (named) if it is absent. */
async function sizeOrFail(path, label) {
	try {
		return (await stat(path)).size;
	} catch (cause) {
		throw new Error(`${label}: cannot stat ${path} (${cause.message})`);
	}
}

/**
 * Compute the stats from the real model file and write the generated module.
 * Fails loudly (rejects) if the file is missing — never emits a fake number.
 */
export async function generateStats({ modelPath: model, outPath }) {
	const modelBytes = await sizeOrFail(model, "model_quantized.onnx");
	const stats = computeStats(modelBytes);
	await mkdir(dirname(outPath), { recursive: true });
	await writeFile(outPath, renderModule(stats));
	return stats;
}

const invokedDirectly =
	process.argv[1] !== undefined &&
	fileURLToPath(import.meta.url) === process.argv[1];

if (invokedDirectly) {
	generateStats({
		modelPath: modelPath(),
		outPath: outputPath(),
	})
		.then((stats) => {
			console.log(
				`Landing stats: ${stats.modelSizeMb} MB model → ${outputPath()}`,
			);
		})
		.catch((err) => {
			console.error(`\nLanding-stats generation FAILED: ${err.message}`);
			process.exit(1);
		});
}
